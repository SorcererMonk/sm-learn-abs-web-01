/**
 * A tiny, dependency-free token pipeline (the job Style Dictionary does):
 * DTCG JSON -> CSS custom properties, with aliases, light/dark modes,
 * fluid clamp() scales and spring easings compiled to linear().
 *
 * Run: node shared/tools/build-tokens.ts  (Node strips the types natively)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { typeStep, spaceStep, type FluidConfig } from '../lib/fluid.ts';
import { springFromDurationBounce, springToLinear } from '../lib/motion.ts';

interface Token {
  $type: string;
  $value: unknown;
  $description?: string;
  $extensions?: Record<string, unknown>;
}

type Tree = { [key: string]: Tree | Token | string | undefined };

interface ShadowLayer {
  offsetX: string;
  offsetY: string;
  blur: string;
  spread: string;
  color: string;
}

interface FluidExtension extends FluidConfig {
  typeSteps: number[];
  space: Record<string, number>;
}

const isToken = (node: unknown): node is Token =>
  typeof node === 'object' && node !== null && '$value' in node;

/** Flattens the tree into [path, token] pairs, skipping $-prefixed metadata keys. */
export function flatten(tree: Tree, prefix: string[] = []): [string[], Token][] {
  return Object.entries(tree).flatMap(([key, node]) => {
    if (key.startsWith('$') || node === undefined || typeof node === 'string') return [];
    if (isToken(node)) return [[[...prefix, key], node]] as [string[], Token][];
    return flatten(node, [...prefix, key]);
  });
}

const cssName = (path: string[]): string => `--${path.join('-')}`;

/** `{color.shadow}` -> `var(--color-shadow)`; aliases stay live in the cascade. */
const resolveAliases = (value: string): string =>
  value.replace(/\{([^}]+)\}/g, (_, ref: string) => `var(${cssName(ref.split('.'))})`);

function formatValue(token: Token): string {
  const { $type, $value } = token;
  switch ($type) {
    case 'fontFamily':
      return ($value as string[])
        .map((f) => (/^[a-z-]+$/i.test(f) && !f.includes(' ') ? f : `"${f}"`))
        .join(', ');
    case 'cubicBezier':
      return `cubic-bezier(${($value as number[]).join(', ')})`;
    case 'shadow':
      return ($value as ShadowLayer[])
        .map((l) => `${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${resolveAliases(l.color)}`)
        .join(', ');
    case 'spring': {
      const { duration, bounce } = $value as { duration: number; bounce: number };
      return springToLinear(springFromDurationBounce(duration, bounce)).easing;
    }
    default:
      return resolveAliases(String($value));
  }
}

export function buildTokensCss(tree: Tree): string {
  const lines: string[] = [];
  for (const [path, token] of flatten(tree)) {
    const name = path[0] === 'brand' && path[1] === 'hue' ? '--brand-hue' : cssName(path);
    const dark = token.$extensions?.['learn.dark'];
    const value =
      typeof dark === 'string'
        ? `light-dark(${formatValue(token)}, ${resolveAliases(dark)})`
        : formatValue(token);
    lines.push(`  ${name}: ${value};`);
    if (token.$type === 'spring') {
      const { duration, bounce } = token.$value as { duration: number; bounce: number };
      const ms = springToLinear(springFromDurationBounce(duration, bounce)).duration;
      lines.push(`  ${name}-duration: ${ms}ms;`);
    }
  }

  const fluidGroup = tree.fluid as Tree & { $extensions: { 'learn.fluid': FluidExtension } };
  const fluid = fluidGroup.$extensions['learn.fluid'];
  for (const step of fluid.typeSteps) {
    lines.push(`  --step-${step < 0 ? `n${-step}` : step}: ${typeStep(fluid, step)};`);
  }
  for (const [name, multiplier] of Object.entries(fluid.space)) {
    lines.push(`  --space-${name}: ${spaceStep(fluid, multiplier)};`);
  }

  return [
    '/* Generated by shared/tools/build-tokens.ts from shared/tokens/tokens.json. Do not edit by hand. */',
    '@layer tokens {',
    '  :root {',
    ...lines.map((l) => `  ${l}`),
    '  }',
    '}',
    '',
  ].join('\n');
}

export const TOKENS_JSON = fileURLToPath(new URL('../tokens/tokens.json', import.meta.url));
export const TOKENS_CSS = fileURLToPath(new URL('../styles/tokens.css', import.meta.url));

export const readTokens = (): Tree => JSON.parse(readFileSync(TOKENS_JSON, 'utf8')) as Tree;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TOKENS_CSS, buildTokensCss(readTokens()));
  console.info(`Wrote ${TOKENS_CSS}`);
}
