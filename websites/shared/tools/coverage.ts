/**
 * Coverage CLI. Usage (from websites/): node shared/tools/coverage.ts --site 01-foundations [--check]
 * Writes <site>/COVERAGE.md (topic-level matrix) and the Part-level matrix inside <site>/README.md
 * between <!-- coverage:start --> and <!-- coverage:end -->. --check fails on any problem.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { computeCoverage, partsTable, topicsTable } from '../lib/coverage.ts';
import type { SiteConfig } from '../lib/site.ts';

const websites = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const repoRoot = resolve(websites, '..');
const args = process.argv.slice(2);
const siteArg = args[args.indexOf('--site') + 1];
if (!siteArg) throw new Error('Pass --site <folder>');
const siteDir = join(websites, siteArg);
const { site } = (await import(pathToFileURL(join(siteDir, 'src/site.ts')).href)) as {
  site: SiteConfig;
};

const coverage = computeCoverage(site, siteDir, repoRoot);
const total = coverage.topics.length;
const complete = coverage.topics.filter((t) => t.status === 'Complete').length;
const summary = `**${complete} of ${total} topics complete** across ${coverage.parts.length} parts/programmes. Generated by \`npm run coverage\` from the source Markdown and the lesson files; a topic is *Complete* only when its page section exists and contains a demo or exercise (see \`shared/lib/coverage.ts\`).`;

writeFileSync(
  join(siteDir, 'COVERAGE.md'),
  [
    `# Coverage matrix: ${site.name}`,
    '',
    summary,
    '',
    'Each row is one topic (one top-level bullet of a PART, or one section of a training/orientation file). `Page/Component` is the route and anchor where it is taught.',
    '',
    topicsTable(coverage, site.name),
    '',
    coverage.problems.length
      ? `## Open problems\n\n${coverage.problems.map((p) => `- ${p}`).join('\n')}`
      : '## Open problems\n\nNone.',
    '',
  ].join('\n'),
);

const readmePath = join(siteDir, 'README.md');
if (existsSync(readmePath)) {
  const readme = readFileSync(readmePath, 'utf8');
  const block = `<!-- coverage:start -->\n${summary}\n\n${partsTable(coverage, site.name)}\n\nFull topic-level matrix: [COVERAGE.md](./COVERAGE.md).\n<!-- coverage:end -->`;
  writeFileSync(
    readmePath,
    readme.replace(/<!-- coverage:start -->[\s\S]*<!-- coverage:end -->/, block),
  );
}

console.info(
  `${site.id}: ${complete}/${total} topics complete, ${coverage.problems.length} problem(s).`,
);
coverage.problems.slice(0, 40).forEach((p) => console.info(`  - ${p}`));
if (args.includes('--check') && coverage.problems.length) process.exit(1);
